#[derive(Clone, Copy, Default)]
pub(super) struct Step {
    pub lead: u8,
    pub bass: u8,
    pub pulse_width: u32,
    pub pulse_high: i32,
    pub pulse_low: i32,
    pub lead_level: i32,
    pub bass_level: i32,
    pub drum_len: u32,
    pub drum_level: i32,
}

/// Resolve a note once per sixteenth, not once per PCM sample.
pub(super) fn step(track: usize, index: u32) -> Step {
    let index = index % STEPS;
    let phrase = index as usize / 32;
    let section = phrase / 4;
    let note = index as usize % 32;
    let pattern = ORDER[phrase];
    let root = ROOTS[track][pattern][note / 8];
    let bass = root
        + if section == 0 || section == 3 {
            0
        } else {
            match note % 8 {
                4 | 5 => 7,
                6 | 7 => 12,
                _ => 0,
            }
        };
    let pulse_width = match section {
        3 => 32768,
        5 => 8192,
        _ => 16384,
    };
    let fill = phrase % 4 == 3 && note >= 28;
    let snare = note % 8 == 4 || fill;
    let drum = if section == 3 {
        note % 8 == 4
    } else {
        note % 2 == 0 || fill
    };
    Step {
        lead: LEADS[track][pattern][note],
        bass,
        pulse_width,
        pulse_high: ((65536 - pulse_width) * 2600 / 65536) as i32,
        pulse_low: -((pulse_width * 2600 / 65536) as i32),
        lead_level: [65, 100, 90, 55, 85, 100][section],
        bass_level: [300, 450, 400, 300, 400, 450][section],
        drum_len: if !drum {
            0
        } else if snare {
            600
        } else {
            160
        },
        drum_level: if snare { 260 } else { 120 },
    }
}
