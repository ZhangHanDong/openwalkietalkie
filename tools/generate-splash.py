#!/usr/bin/env python3
"""Generate the boot branding from the website icon, hero font and COHDL mark.

Requires CairoSVG, Pillow and fontTools[woff]. The radio keeps the website's
16-pixel grid; the title uses its OFL-licensed Press Start 2P font. Only the
symbol group of the supplied COHDL SVG is used beside the project credit.
Normal firmware builds use checked-in bitmaps and need no graphics packages.
"""
import hashlib
import io
from pathlib import Path
import struct
import xml.etree.ElementTree as ET

import cairosvg
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
LOGO = ROOT / "site/public/assets/logo-64.png"
FONT = ROOT / "site/public/fonts/press-start-2p-latin.woff2"
COHDL = ROOT / "assets/CoHDL-透明白2k.svg"
TITLE_SIZE = 40
TITLE_PITCH = 48
COHDL_HEIGHT = 28


def cohdl_mark():
    svg = ET.fromstring(COHDL.read_bytes())
    # The source has two top-level groups: symbol, then outlined wordmark.
    _symbol, wordmark = list(svg)
    svg.remove(wordmark)
    png = cairosvg.svg2png(
        bytestring=ET.tostring(svg), output_width=1920, output_height=1440
    )
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    bounds = alpha.getbbox()
    if bounds is None:
        raise ValueError("The COHDL mark is empty")
    alpha = alpha.crop(bounds)
    width = round(alpha.width * COHDL_HEIGHT / alpha.height)
    return alpha.resize((width, COHDL_HEIGHT), Image.Resampling.LANCZOS)


def title():
    ttf = TTFont(FONT)
    ttf.flavor = None
    data = io.BytesIO()
    ttf.save(data)
    data.seek(0)
    font = ImageFont.truetype(data, TITLE_SIZE)
    lines = ("OPEN", "WALKIE", "TALKIE")
    alpha = Image.new("L", (6 * TITLE_SIZE, 2 * TITLE_PITCH + TITLE_SIZE))
    draw = ImageDraw.Draw(alpha)
    for row, line in enumerate(lines):
        draw.text(
            ((alpha.width - draw.textlength(line, font=font)) / 2, row * TITLE_PITCH),
            line, font=font, fill=255,
        )
    return alpha


def main():
    generated = "// Generated by tools/generate-splash.py. Do not edit.\n"
    for source in (LOGO, FONT, COHDL):
        generated += f"// {source.relative_to(ROOT)} SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n"

    def asset(name, bitmap, data, suffix):
        nonlocal generated
        path = f"assets/splash-{name.lower()}.{suffix}"
        (ROOT / path).write_bytes(data)
        generated += (
            f"pub const {name}_WIDTH: u16 = {bitmap.width};\n"
            f"pub const {name}_HEIGHT: u16 = {bitmap.height};\n"
            f'pub static {name}: &[u8; {len(data)}] = include_bytes!("../../{path}");\n'
        )
        print(f"{path}: {bitmap.width}×{bitmap.height}, {len(data):,} bytes")

    # Recover the original pixel grid losslessly, then trim transparent margins.
    radio = Image.open(LOGO).convert("RGBA")
    grid = radio.resize((16, 16), Image.Resampling.NEAREST)
    if grid.resize(radio.size, Image.Resampling.NEAREST).tobytes() != radio.tobytes():
        raise ValueError("Website icon no longer uses a 16×16 pixel grid")
    grid = grid.crop(grid.getbbox())
    black = Image.new("RGBA", grid.size, (0, 0, 0, 255))
    radio = Image.alpha_composite(black, grid).convert("RGB")
    rgb565 = b"".join(
        struct.pack("<H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
        for r, g, b in radio.getdata()
    )
    asset("RADIO", radio, rgb565, "rgb565")
    heading = title()
    asset("TITLE", heading, heading.tobytes(), "alpha")
    generated += f"pub const TITLE_ACCENT_Y: u16 = {2 * TITLE_PITCH};\n"
    mark = cohdl_mark()
    asset("COHDL", mark, mark.tobytes(), "alpha")
    (ROOT / "src/ui/splash_asset.rs").write_text(generated)


if __name__ == "__main__":
    main()
