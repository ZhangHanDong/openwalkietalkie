#!/usr/bin/env python3
"""Render the supplied CoHDL SVG to the firmware's white-on-black alpha mask.

Requires CairoSVG and Pillow. Only transparent margins are trimmed; the logo
paths and their relative positions come directly from the source SVG.
Normal firmware builds use the checked-in mask and need no SVG renderer.
"""
import hashlib
import io
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/CoHDL-透明白2k.svg"
WIDTH = 360


def main():
    source = SOURCE.read_bytes()
    png = cairosvg.svg2png(bytestring=source, output_width=1920, output_height=1440)
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    bounds = alpha.getbbox()
    if bounds is None:
        raise ValueError("The splash logo is empty")
    alpha = alpha.crop(bounds)
    height = round(alpha.height * WIDTH / alpha.width)
    alpha = alpha.resize((WIDTH, height), Image.Resampling.LANCZOS)
    (ROOT / "assets/cohdl-splash.alpha").write_bytes(alpha.tobytes())
    digest = hashlib.sha256(source).hexdigest()
    (ROOT / "src/ui/splash_asset.rs").write_text(
        f'// Generated by tools/generate-splash.py from {SOURCE.name}.\n'
        f'// Source SHA-256: {digest}\n'
        f'pub const WIDTH: u16 = {WIDTH};\n'
        f'pub const HEIGHT: u16 = {height};\n'
        f'pub static ALPHA: &[u8; {WIDTH * height}] = '
        'include_bytes!("../../assets/cohdl-splash.alpha");\n'
    )
    print(f"Generated CoHDL splash: {WIDTH}×{height}, {WIDTH * height:,} bytes")


if __name__ == "__main__":
    main()
